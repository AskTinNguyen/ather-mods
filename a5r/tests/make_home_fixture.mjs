// Regenerates tests/home.fixture.ts from Ather's own Home builders (ather-automata/hooks/rows.mjs masthead and
// summaryStrip, crew-rows.mjs crewSections, home.mjs isShownIn and the view labels), assembled in the order Ather's
// console.mjs draws Home, in its Simple and Advanced views on the desktop and the terminal (A30, 0.18.3): the test runner
// cannot import outside the a5r folder. Run from the repository root: node a5r/tests/make_home_fixture.mjs
import fs from 'node:fs'
import { label, masthead, section, summaryStrip } from '../../ather-automata/hooks/rows.mjs'
import { crewSections } from '../../ather-automata/hooks/crew-rows.mjs'
import { VIEW_LABELS, isShownIn, otherView } from '../../ather-automata/hooks/home.mjs'

const version = JSON.parse(fs.readFileSync(new URL('../../ather-automata/.claude-plugin/plugin.json', import.meta.url), 'utf8')).version
// The element factory the engine hands a pane, as the plain nodes a pane hook returns: functions dropped (the fixture is
// data), no `key` on a Text (the engine's Text takes none), no children on a leaf.
const make = type => (p = {}) => {
  const { children, ...rest } = p
  const props = Object.fromEntries(Object.entries(rest).filter(([k, v]) => typeof v !== 'function' && !(type === 'Text' && k === 'key')))
  const kids = children === undefined ? [] : Array.isArray(children) ? children : [children]
  return kids.length > 0 ? { type, props, children: kids } : { type, props }
}
// A Button is a live element the engine holds for the plugin that drew it; a fixture cannot carry one, so it is kept as a
// keyed Box holding its label (its place and key in the tree are what A5R's wrapper reads).
const button = (p = {}) => ({ type: 'Box', props: { key: p.key }, children: [{ type: 'Text', props: {}, children: [String(p.label ?? '')] }] })
const el = { Box: make('Box'), Text: make('Text'), Button: button, Svg: make('Svg') }
const CREW = [{ id: 'w1', title: 'Build the editor target', kind: 'builder', model: 'sonnet', state: 'running', prop: null, trail: [], origin: 'seen', elapsed: 30000, tools: 3, via: '', parentId: '', wait: '', stuck: '' }]
const MODEL = { header: { done: 3, total: 7 }, open: [], work: [] }

const home = (view, surface) => {
  const isClicked = surface === 'desktop'
  const width = 60
  const shown = list => list.filter(([part]) => isShownIn(view, part)).flatMap(([, nodes]) => nodes)
  const rows = [masthead(el, shown([['title', [el.Text({ key: 'title', bold: true, children: 'What next?' })]], ['status', [el.Text({ key: 'status', children: 'Build · 3/7' })]]]), surface)]
  const parts = []
  parts.push(['strip', [summaryStrip(el, MODEL, CREW, isClicked)]])
  parts.push(['next', [section(el, 'next-section', [label(el, 'next-label', 'Next', width), el.Text({ children: 'Prove it in PIE' })])]])
  parts.push(['crew', crewSections(el, { crew: CREW, width, isClicked, onWorker: () => () => undefined })])
  parts.push(['view', [section(el, 'view', [el.Button({ key: 'view-toggle', label: VIEW_LABELS[otherView(view)], plain: true })])]])
  rows.push(...shown(parts), el.Box({ key: 'foot', children: [el.Text({ children: 'Esc closes' })] }))
  return el.Box({ flexDirection: 'column', children: rows })
}
const trees = {}
for (const view of ['simple', 'advanced']) for (const surface of ['desktop', 'terminal']) trees[`${view}-${surface}`] = home(view, surface)
const out = `// Generated by tests/make_home_fixture.mjs from Ather ${version}'s own Home builders; do not edit by hand.
export const ATHER_VERSION = ${JSON.stringify(version)}
export const HOMES: Record<string, unknown> = ${JSON.stringify(trees, null, 1)}
`
fs.writeFileSync(new URL('./home.fixture.ts', import.meta.url), out)
console.log(`home.fixture.ts: Ather ${version}, ${Object.keys(trees).length} homes`)
